    def bootstrap():
        d=payload()
        if limited('setup:'+request.remote_addr,8):return fail('Muitas tentativas; aguarde 5 minutos.',429)
        if g.s.scalar(select(func.count()).select_from(User)):return fail('Instalação já configurada.',409)
        expected=os.getenv('SETUP_TOKEN','')
        if not expected or not secrets.compare_digest(d.get('setup_token',''),expected):return fail('Token de instalação inválido. Use o token gerado pelo instalador.',403)
        email=d.get('email','').strip().lower();password=d.get('password','')
        if '@' not in email or len(email)>250 or len(password)<12:raise ValueError('Informe e-mail e senha com no mínimo 12 caracteres.')
        # Singleton insert serializes concurrent bootstrap requests.
        g.s.add(Setting(key='bootstrap_completed',value='1'));g.s.flush()
        g.s.add(User(email=email,password=generate_password_hash(password),role='superadmin'))
        g.s.commit();return jsonify(ok=True)
