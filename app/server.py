    def registration_has_records(coid):
        # Preserve every dependent fiscal/agent record, including extension tables.
        for mapper in Base.registry.mappers:
            model=mapper.class_
            if model in (Member,ClientRegistration,Audit) or not hasattr(model,'company_id'):continue
            if g.s.scalar(select(model.company_id).where(model.company_id==coid).limit(1)):return True
        if g.s.get(Setting,'capture-registration:'+coid):return True
        return False
    def clear_registration_operations(coid):
        from .agent_bridge import AgentDevice,AgentCompanyLink,CompanyCertificate,CertificateTask
        from .distribution import DistributionTask,DistributionState,CaptureBatch,CaptureDispatch,CaptureItem
        from .client_capture import StoredA1
        from .fiscal_history import FiscalArchive
        docs=g.s.scalar(select(func.count()).select_from(Document).where(Document.company_id==coid))
        history=g.s.scalar(select(func.count()).select_from(FiscalArchive).where(FiscalArchive.company_id==coid))
        if docs or history:
            raise ValueError(f'Este CNPJ/CPF ainda possui {docs} documento(s) em Documentos e {history} arquivo(s) no Histórico fiscal. Nenhum arquivo foi apagado.')
        running=g.s.scalar(select(DistributionTask.id).where(DistributionTask.company_id==coid,DistributionTask.state=='running',DistributionTask.expires>time.time()).limit(1))
        if running:raise ValueError('Existe uma consulta em andamento para este CNPJ/CPF. Pare as próximas consultas e aguarde a atual terminar antes de excluir.')
        batches=select(CaptureBatch.id).where(CaptureBatch.company_id==coid)
        tasks=select(DistributionTask.id).where(DistributionTask.company_id==coid)
        g.s.execute(delete(CaptureDispatch).where(or_(CaptureDispatch.batch_id.in_(batches),CaptureDispatch.task_id.in_(tasks))))
        g.s.execute(delete(CaptureItem).where(CaptureItem.batch_id.in_(batches)))
        for model in (CaptureBatch,DistributionTask,DistributionState,CompanyCertificate,StoredA1,AgentCompanyLink):
            g.s.execute(delete(model).where(model.company_id==coid))
        g.s.execute(delete(Setting).where(Setting.key=='capture-registration:'+coid))
        for dev in g.s.scalars(select(AgentDevice).where(AgentDevice.company_id==coid)).all():
            other=g.s.scalar(select(AgentCompanyLink.company_id).where(AgentCompanyLink.device_id==dev.id).order_by(AgentCompanyLink.company_id).limit(1))
            if other:dev.company_id=other
            else:
                g.s.execute(delete(CertificateTask).where(CertificateTask.device_id==dev.id))
                g.s.delete(dev)
        g.s.flush()
