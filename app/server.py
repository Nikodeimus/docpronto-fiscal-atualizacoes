    def fail(message,status=400):return jsonify(error=message),status
    def digest(t):return hashlib.sha256(t.encode()).hexdigest()
    @app.before_request
    def guard():
        if request.content_length and request.content_length>64*1024*1024:return fail('Upload excede 64 MB.',413)
        if not testing and request.host.split(':')[0] not in os.getenv('ALLOWED_HOSTS','localhost,127.0.0.1').split(','):return fail('Host não autorizado.',400)
        if request.method not in ('GET','HEAD','OPTIONS'):
            origin=request.headers.get('Origin')
            if origin and origin!=request.host_url.rstrip('/'):return fail('Origem não autorizada.',403)
        if request.path.startswith('/api/') and request.method not in ('GET','HEAD','OPTIONS') and request.is_json:
            if not isinstance(request.get_json(silent=True),dict):return fail('Corpo JSON inválido.',400)
        g.s=Session()
        if not request.path.startswith('/api/') or request.path in ('/api/login','/api/bootstrap','/api/status','/api/signup') or re.fullmatch(r'/api/invites/[A-Za-z0-9_-]{20,100}(?:/accept)?',request.path) or request.path.startswith('/api/agent/'):return
        token=request.cookies.get('docpronto_session','')
        session=g.s.get(Login,digest(token)) if token else None
        if not session or session.expires<time.time():return fail('Entre para continuar.',401)
        g.user=g.s.get(User,session.user_id);g.login=session
        if request.method not in ('GET','HEAD','OPTIONS') and not secrets.compare_digest(request.headers.get('X-CSRF-Token',''),session.csrf):return fail('Sessão expirada ou proteção CSRF inválida.',403)
