    def limited(key,limit=15):
        now=time.time();bucket=f'{key}:{int(now//300)}'
        record=g.s.get(RateBucket,bucket)
        if record is None:
            g.s.add(RateBucket(key=bucket,expires=now+600,count=1));g.s.flush()
        else:
            updated=g.s.execute(update(RateBucket).where(RateBucket.key==bucket,RateBucket.count<limit).values(count=RateBucket.count+1)).rowcount
            if not updated:return True
        g.s.execute(delete(RateBucket).where(RateBucket.expires<now));g.s.commit();return False
